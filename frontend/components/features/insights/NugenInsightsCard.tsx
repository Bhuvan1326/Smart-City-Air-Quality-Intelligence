"use client";

import { useEffect, useState } from "react";
import { Sparkles, Loader2, AlertCircle, RefreshCw } from "lucide-react";
import {
  insightsApi,
  type AirQualityInsight,
  type AirQualityInsightRequest,
} from "@/lib/api/services";

const AUDIENCES = [
  { id: "citizen", label: "Citizen" },
  { id: "officer", label: "Officer" },
  { id: "admin", label: "Admin" },
] as const;

const INSIGHTS_HISTORY_KEY = "nugen-air-quality-insights-history";
const MAX_HISTORY_ENTRIES = 20;

type InsightHistoryEntry = {
  id: string;
  generatedAt: string;
  request: AirQualityInsightRequest;
  result: AirQualityInsight;
};

export default function NugenInsightsCard({
  defaultCity = "Pune",
}: {
  defaultCity?: string;
}) {
  const [city, setCity] = useState(defaultCity);
  const [aqi, setAqi] = useState("");
  const [pm25, setPm25] = useState("");
  const [audience, setAudience] =
    useState<AirQualityInsightRequest["audience"]>("citizen");
  const [question, setQuestion] = useState("");
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const [result, setResult] = useState<AirQualityInsight | null>(null);
  const [history, setHistory] = useState<InsightHistoryEntry[]>([]);

  useEffect(() => {
    try {
      const stored = window.localStorage.getItem(INSIGHTS_HISTORY_KEY);
      if (!stored) return;

      const parsed: unknown = JSON.parse(stored);
      if (!Array.isArray(parsed)) return;

      const entries = parsed.filter(
        (entry): entry is InsightHistoryEntry => {
          if (typeof entry !== "object" || entry === null) return false;
          const candidate = entry as Record<string, unknown>;
          const request = candidate.request;
          const storedResult = candidate.result;
          return (
            typeof candidate.id === "string" &&
            typeof candidate.generatedAt === "string" &&
            typeof request === "object" &&
            request !== null &&
            typeof storedResult === "object" &&
            storedResult !== null &&
            typeof (storedResult as Record<string, unknown>).insight ===
              "string"
          );
        },
      );
      setHistory(entries.slice(0, MAX_HISTORY_ENTRIES));
      const latest = entries[0];
      if (latest) {
        setCity(latest.request.city ?? defaultCity);
        setAqi(latest.request.aqi?.toString() ?? "");
        setPm25(latest.request.pm25?.toString() ?? "");
        setAudience(latest.request.audience ?? "citizen");
        setQuestion(latest.request.question ?? "");
        setResult(latest.result);
      }
    } catch (e) {
      console.warn("Unable to restore Nugen insight history.", e);
    }
  }, [defaultCity]);

  const saveHistory = (nextHistory: InsightHistoryEntry[]) => {
    setHistory(nextHistory);
    try {
      window.localStorage.setItem(
        INSIGHTS_HISTORY_KEY,
        JSON.stringify(nextHistory),
      );
    } catch (e) {
      console.warn("Unable to save Nugen insight history.", e);
    }
  };

  const run = async () => {
    setLoading(true);
    setError(null);
    try {
      const payload: AirQualityInsightRequest = {
        city: city || undefined,
        aqi: aqi ? Number(aqi) : undefined,
        pm25: pm25 ? Number(pm25) : undefined,
        audience,
        question: question || undefined,
      };
      const nextResult = await insightsApi.airQuality(payload);
      setResult(nextResult);
      saveHistory(
        [
          {
            id: `${Date.now()}-${Math.random().toString(36).slice(2)}`,
            generatedAt: new Date().toISOString(),
            request: payload,
            result: nextResult,
          },
          ...history,
        ].slice(0, MAX_HISTORY_ENTRIES),
      );
    } catch (e: unknown) {
      const msg =
        (e as { response?: { data?: { detail?: string } } })?.response?.data
          ?.detail ??
        "Insight generation failed. The Nugen-aligned model may be unreachable.";
      setError(msg);
      setResult(null);
    } finally {
      setLoading(false);
    }
  };

  const selectHistoryEntry = (entry: InsightHistoryEntry) => {
    setCity(entry.request.city ?? defaultCity);
    setAqi(entry.request.aqi?.toString() ?? "");
    setPm25(entry.request.pm25?.toString() ?? "");
    setAudience(entry.request.audience ?? "citizen");
    setQuestion(entry.request.question ?? "");
    setResult(entry.result);
    setError(null);
  };

  const num = (v: string) => v.replace(/[^\d.]/g, "");

  return (
    <div className="rounded-xl border border-slate-200 bg-white/90 backdrop-blur-sm p-5 sm:p-6 shadow-sm">
      <div className="flex items-center gap-2 mb-1">
        <Sparkles className="w-5 h-5 text-blue-600" aria-hidden="true" />
        <h2 className="text-lg font-semibold text-slate-900">
          Air Quality Insights
        </h2>
      </div>
      <p className="text-sm text-slate-500 mb-5">
        Generated by the deployed Nugen domain-aligned model.
      </p>

      <div className="grid grid-cols-2 sm:grid-cols-4 gap-3 mb-4">
        <label className="block text-xs font-medium text-slate-600">
          City
          <input
            value={city}
            onChange={(e) => setCity(e.target.value)}
            className="mt-1 w-full rounded-lg border border-slate-300 px-3 py-2 text-sm text-slate-900 focus:outline-none focus:ring-2 focus:ring-blue-500"
            placeholder="Pune"
          />
        </label>
        <label className="block text-xs font-medium text-slate-600">
          AQI (optional)
          <input
            value={aqi}
            onChange={(e) => setAqi(num(e.target.value))}
            inputMode="numeric"
            className="mt-1 w-full rounded-lg border border-slate-300 px-3 py-2 text-sm text-slate-900 focus:outline-none focus:ring-2 focus:ring-blue-500"
            placeholder="e.g. 165"
          />
        </label>
        <label className="block text-xs font-medium text-slate-600">
          PM2.5 µg/m³ (optional)
          <input
            value={pm25}
            onChange={(e) => setPm25(num(e.target.value))}
            inputMode="numeric"
            className="mt-1 w-full rounded-lg border border-slate-300 px-3 py-2 text-sm text-slate-900 focus:outline-none focus:ring-2 focus:ring-blue-500"
            placeholder="e.g. 72"
          />
        </label>
        <div className="block text-xs font-medium text-slate-600">
          Audience
          <div className="mt-1 flex rounded-lg border border-slate-300 overflow-hidden">
            {AUDIENCES.map((a) => (
              <button
                key={a.id}
                type="button"
                onClick={() => setAudience(a.id)}
                className={`flex-1 px-2 py-2 text-xs font-medium transition-colors focus:outline-none focus:ring-2 focus:ring-blue-500 ${
                  audience === a.id
                    ? "bg-blue-600 text-white"
                    : "bg-white text-slate-600 hover:bg-slate-100"
                }`}
              >
                {a.label}
              </button>
            ))}
          </div>
        </div>
      </div>

      <label className="block text-xs font-medium text-slate-600 mb-3">
        Question (optional)
        <input
          value={question}
          onChange={(e) => setQuestion(e.target.value)}
          className="mt-1 w-full rounded-lg border border-slate-300 px-3 py-2 text-sm text-slate-900 focus:outline-none focus:ring-2 focus:ring-blue-500"
          placeholder="Explain current air-quality conditions and what to do."
        />
      </label>

      <button
        type="button"
        onClick={run}
        disabled={loading}
        className="w-full sm:w-auto px-4 py-2.5 rounded-lg bg-blue-600 hover:bg-blue-700 text-white text-sm font-medium transition-colors focus:outline-none focus:ring-2 focus:ring-blue-500 disabled:opacity-60 disabled:cursor-not-allowed flex items-center justify-center gap-2"
      >
        {loading ? (
          <Loader2 className="w-4 h-4 animate-spin" aria-hidden="true" />
        ) : (
          <Sparkles className="w-4 h-4" aria-hidden="true" />
        )}
        {loading ? "Generating..." : "Generate insight"}
      </button>

      {error && (
        <div
          role="alert"
          className="mt-4 flex items-start gap-2 px-4 py-3 rounded-lg bg-red-50 border border-red-200 text-red-700 text-sm"
        >
          <AlertCircle className="w-4 h-4 mt-0.5 flex-shrink-0" />
          <span>{error}</span>
        </div>
      )}

      {result && (
        <div className="mt-5 rounded-lg bg-slate-50 border border-slate-200 p-4">
          <div className="whitespace-pre-wrap text-sm text-slate-800 leading-relaxed">
            {result.insight}
          </div>
          <div className="mt-3 pt-3 border-t border-slate-200 flex flex-wrap items-center gap-x-4 gap-y-1 text-xs text-slate-500">
            <span title="Aligned model serving this inference">
              Model: <code className="text-slate-700">{result.model_id}</code>
            </span>
            {result.confidence_score != null && (
              <span>
                Confidence: {(result.confidence_score * 100).toFixed(0)}%
              </span>
            )}
            <button
              type="button"
              onClick={run}
              className="ml-auto inline-flex items-center gap-1 text-blue-600 hover:text-blue-700 font-medium focus:outline-none focus:ring-2 focus:ring-blue-500 rounded"
            >
              <RefreshCw className="w-3 h-3" aria-hidden="true" />
              Regenerate
            </button>
          </div>
        </div>
      )}

      {history.length > 0 && (
        <div className="mt-5 border-t border-slate-200 pt-4">
          <h3 className="text-sm font-semibold text-slate-800">
            Insight history
          </h3>
          <div className="mt-2 space-y-2">
            {history.map((entry) => (
              <button
                key={entry.id}
                type="button"
                onClick={() => selectHistoryEntry(entry)}
                className="w-full rounded-lg border border-slate-200 bg-slate-50 px-3 py-2 text-left transition-colors hover:bg-slate-100 focus:outline-none focus:ring-2 focus:ring-blue-500"
              >
                <span className="block text-xs font-medium text-slate-700">
                  {entry.request.city ?? defaultCity} ·{" "}
                  {entry.request.audience ?? "citizen"}
                </span>
                <span className="mt-1 block truncate text-xs text-slate-500">
                  {entry.result.insight}
                </span>
                <span className="mt-1 block text-[11px] text-slate-400">
                  {new Date(entry.generatedAt).toLocaleString()}
                </span>
              </button>
            ))}
          </div>
        </div>
      )}
    </div>
  );
}
